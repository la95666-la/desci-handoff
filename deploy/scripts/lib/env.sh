# check_deps 检查本地依赖
check_deps() {
    local missing=()
    for cmd in ssh scp git tar; do
        command -v "$cmd" >/dev/null 2>&1 || missing+=("$cmd")
    done
    if [ ${#missing[@]} -gt 0 ]; then
        error "缺少依赖: ${missing[*]}"
        exit 1
    fi
}

