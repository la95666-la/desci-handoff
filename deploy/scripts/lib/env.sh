#!/usr/bin/env bash
# .deploy.env 读写 + 远端命令执行 helpers

env_file_exists() { [ -f "$JC_ENV_FILE" ]; }

load_env() {
    if ! env_file_exists; then
        error "尚未部署 —— 请先运行: ./deploy.sh install"
        exit 1
    fi
    # set -a: source 后自动 export，让 envsubst / 子进程能读到 JC_* 变量
    set -a
    # shellcheck disable=SC1090
    source "$JC_ENV_FILE"
    set +a
    : "${JC_HOST:?}" "${JC_REMOTE:?}" "${JC_SSH_USER:=root}" "${JC_COMPOSE_PROJECT:=joincare}"
    validate_deploy_target || exit 2
}

validate_deploy_target() {
    [[ "${JC_SSH_USER:-}" =~ ^[a-z_][a-z0-9_-]{0,31}$ ]] || {
        error "JC_SSH_USER格式无效"
        return 2
    }
    validate_ssh_host "${JC_HOST:-}" || {
        error "JC_HOST格式无效"
        return 2
    }
    [[ "${JC_REMOTE:-}" =~ ^/[A-Za-z0-9._/-]+$ ]] && [[ "$JC_REMOTE" != *"//"* ]] && [[ "$JC_REMOTE" != */../* ]] && [[ "$JC_REMOTE" != */.. ]] && [[ "$JC_REMOTE" != *"/./"* ]] || {
        error "JC_REMOTE必须是无遍历、无空格或shell字符的绝对Unix路径"
        return 2
    }
    [[ "${JC_COMPOSE_PROJECT:-}" =~ ^[a-z0-9][a-z0-9_-]{0,62}$ ]] || {
        error "JC_COMPOSE_PROJECT格式无效"
        return 2
    }
}

validate_ssh_host() {
    local host="${1:-}" part
    local -a parts
    [ -n "$host" ] && [ "${#host}" -le 253 ] || return 2
    # IPv6 is accepted only as a bracketed literal and must contain at least one
    # colon. The character set deliberately excludes zone IDs, ports and options.
    if [[ "$host" =~ ^\[[0-9A-Fa-f:]+\]$ ]]; then
        [[ "$host" == *:* ]] && [[ "$host" != *:::* ]]
        return
    fi
    # Dotted-decimal IPv4 requires exactly four numeric octets in range.
    if [[ "$host" =~ ^[0-9]+(\.[0-9]+){3}$ ]]; then
        IFS=. read -r -a parts <<< "$host"
        [ "${#parts[@]}" -eq 4 ] || return 2
        for part in "${parts[@]}"; do
            [ "${#part}" -le 3 ] && [ "$part" -le 255 ] || return 2
        done
        return 0
    fi
    # DNS labels are 1..63 characters, alnum at both ends, with only interior '-'.
    [[ "$host" != .* && "$host" != *. && "$host" != *..* ]] || return 2
    IFS=. read -r -a parts <<< "$host"
    [ "${#parts[@]}" -gt 0 ] || return 2
    for part in "${parts[@]}"; do
        [ -n "$part" ] && [ "${#part}" -le 63 ] &&
            [[ "$part" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?$ ]] || return 2
    done
}

# save_env KEY VALUE —— 覆盖或追加到 .deploy.env
save_env() {
    local key="$1" val="$2"
    touch "$JC_ENV_FILE"
    chmod 600 "$JC_ENV_FILE"
    # 值加单引号 + 转义内部单引号（防含空格 / 特殊字符如 ::/0 被 source 时当命令）
    local escaped
    escaped=$(printf "%s" "$val" | sed "s/'/'\\\\''/g")
    if grep -q "^${key}=" "$JC_ENV_FILE"; then
        sed -i "s|^${key}=.*|${key}='${escaped}'|" "$JC_ENV_FILE"
    else
        echo "${key}='${escaped}'" >> "$JC_ENV_FILE"
    fi
}

# save_env_batch —— 从 export 出来的变量批量保存
# 用法: save_env_batch VAR1 VAR2 VAR3 ...
save_env_batch() {
    for key in "$@"; do
        # 未 set 的变量写空串，避免 set -u 崩（Twitter/Reown/TG 常留空）
        save_env "$key" "${!key:-}"
    done
}

