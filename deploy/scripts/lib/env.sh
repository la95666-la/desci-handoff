# render_template 用 envsubst 渲染模板到目标（保留 \$var 转义）
# 用法: render_template SRC DST
render_template() {
    local src="$1" dst="$2"
    if ! command -v envsubst >/dev/null 2>&1; then
        error "本地缺少 envsubst (来自 gettext)"
        exit 1
    fi
    mkdir -p "$(dirname "$dst")"
    envsubst < "$src" > "$dst"
}
