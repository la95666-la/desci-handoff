#!/usr/bin/env node
/**
 * 把 joincare-web 的 src/i18n/*.js 中所有 TRANSLATIONS 导入到 copywriting_config。
 *   - key 形态：`<page>.<originalKey>`（如 home.heroEyebrow）
 *   - 仅写入 en + tw 两种语言
 *   - 使用 INSERT ... ON DUPLICATE KEY UPDATE，幂等
 *
 * 用法：node seed-copywriting.mjs > out.sql
 *       Import is intentionally unavailable until a reviewed root-owned MySQL defaults-file transport is provided.
 */
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const I18N_DIR = path.resolve(
  __dirname,
  '../../joincare_code/joincare_code/_extracted/joincare_frontend-main/joincare-web/src/i18n',
);

const FILES = [
  'navbar.js',
  'home.js',
  'ecosystem.js',
  'launchpad.js',
  'taskhall.js',
  'projectapply.js',
];

function escapeSqlString(s) {
  if (typeof s !== 'string') s = String(s ?? '');
  return s.replaceAll('\\', '\\\\').replaceAll("'", "\\'");
}

function emitForPage(prefix, t) {
  const en = t?.en ?? {};
  const tw = t?.tw ?? {};
  // zh（简中）：若 i18n 文件里没有 zh 段，用 tw 兜底（admin 后续可编辑覆盖）
  const zh = t?.zh ?? tw;
  const keys = new Set([...Object.keys(en), ...Object.keys(tw), ...Object.keys(zh)]);
  const lines = [];
  for (const k of keys) {
    const fullKey = `${prefix}.${k}`;
    const enVal = en[k] ?? '';
    const twVal = tw[k] ?? '';
    const zhVal = zh[k] ?? twVal;
    if (typeof enVal === 'object' || typeof twVal === 'object' || typeof zhVal === 'object') continue; // skip nested arrays
    lines.push(
      `INSERT INTO copywriting_config (\`key\`, language, value) VALUES ('${escapeSqlString(fullKey)}', 'en', '${escapeSqlString(enVal)}') ON DUPLICATE KEY UPDATE value=VALUES(value);`,
    );
    lines.push(
      `INSERT INTO copywriting_config (\`key\`, language, value) VALUES ('${escapeSqlString(fullKey)}', 'tw', '${escapeSqlString(twVal)}') ON DUPLICATE KEY UPDATE value=VALUES(value);`,
    );
    lines.push(
      `INSERT INTO copywriting_config (\`key\`, language, value) VALUES ('${escapeSqlString(fullKey)}', 'zh', '${escapeSqlString(zhVal)}') ON DUPLICATE KEY UPDATE value=VALUES(value);`,
    );
  }
  return lines;
}

const out = ['-- auto-generated by seed-copywriting.mjs', 'SET NAMES utf8mb4;'];
for (const f of FILES) {
  const filePath = path.join(I18N_DIR, f);
  const prefix = path.basename(f, '.js');
  try {
    const mod = await import(pathToFileURL(filePath).href);
    const t = mod.TRANSLATIONS;
    if (!t) {
      console.error(`! ${f}: no TRANSLATIONS export`);
      continue;
    }
    const lines = emitForPage(prefix, t);
    out.push(`-- ${f}: ${lines.length / 2} keys`);
    out.push(...lines);
  } catch (e) {
    console.error(`! ${f}: ${e.message}`);
  }
}

process.stdout.write(out.join('\n') + '\n');
